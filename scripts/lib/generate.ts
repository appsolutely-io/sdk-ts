import { readFileSync } from 'node:fs';
import openapiTS, {
  astToString,
  resolveRef,
  type Method,
  type OpenAPI3,
  type OperationObject,
  type ParameterObject,
  type PathItemObject,
  type ReferenceObject,
} from 'openapi-typescript';
import { parse } from 'yaml';
import { GENERATED_FILE } from './spec.ts';

const HEADER = '// Generated by `pnpm generate` from spec/openapi.yaml. Do not edit by hand.\n\n';

function keyedOperations(document: OpenAPI3): string[] {
  function resolve<T>(value: T | ReferenceObject): T {
    if (value !== null && typeof value === 'object' && '$ref' in value && typeof value.$ref === 'string') {
      const resolved = resolveRef<T>(document, value.$ref, { silent: false });
      if (resolved === undefined) {
        throw new Error(`Cannot resolve ${value.$ref} while generating keyed operations.`);
      }
      return resolved;
    }
    return value as T;
  }

  const keyed: string[] = [];
  const methods: Method[] = ['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace'];
  for (const [path, value] of Object.entries(document.paths ?? {})) {
    const item = resolve<PathItemObject>(value);
    for (const method of methods) {
      const operation = item[method];
      if (operation === undefined) continue;
      const parameters = new Map<string, ParameterObject>();
      for (const value of [...(item.parameters ?? []), ...(resolve<OperationObject>(operation).parameters ?? [])]) {
        const parameter = resolve<ParameterObject>(value);
        parameters.set(`${parameter.in}-${parameter.name}`, parameter);
      }
      if (parameters.get('header-Idempotency-Key')?.required === true) {
        keyed.push(`${method.toUpperCase()} ${path}`);
      }
    }
  }
  return keyed.sort();
}

/**
 * The client types and runtime keyed operations for a document: `paths`, `components` and `operations`, plus every
 * component schema as a root type under its own name, so a consumer imports `Article`
 * rather than reaching into `components['schemas']`.
 */
export async function generateSchema(text: string): Promise<string> {
  const document: OpenAPI3 = parse(text);
  const nodes = await openapiTS(document, { rootTypes: true, rootTypesNoSchemaPrefix: true });
  const registry = Object.fromEntries(keyedOperations(document).map((operation) => [operation, true]));
  return (
    HEADER + astToString(nodes) + `\nexport const keyedOperations = ${JSON.stringify(registry, null, 4)} as const;\n`
  );
}

/** Why the committed client types are not what the document generates, or null when they are. */
export async function generatedDrift(document: string): Promise<string | null> {
  let committed = '';
  try {
    committed = readFileSync(GENERATED_FILE, 'utf8');
  } catch {
    // A missing file differs from any generated output.
  }
  return committed === (await generateSchema(document))
    ? null
    : 'src/generated/schema.ts is not what spec/openapi.yaml generates; run pnpm generate.';
}
